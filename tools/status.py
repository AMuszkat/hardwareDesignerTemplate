"""
Write the generated block of design/STATUS.md (between the STATUS:GENERATED
markers): each board's component status from its value bus, each board's
handoff freshness, and the diagram sheets with the decision each one reflects.
Run after any change that moves them.

    .venv/bin/python tools/status.py            # write the block
    .venv/bin/python tools/status.py --check    # exit 1 if the block is not current

The block is DETERMINISTIC -- no timestamps, no file dates -- so the doc lint
(check 9) can tell a stale block from a current one, and re-running it changes
nothing.
"""
import importlib
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "studies"))
PY = sys.executable
BOARDS = os.path.join(HERE, "handoff", "boards")
A, B = "<!-- STATUS:GENERATED -->", "<!-- /STATUS:GENERATED -->"


def boards():
    if not os.path.isdir(BOARDS):
        return []
    return sorted((f[:-3] for f in os.listdir(BOARDS)
                   if re.fullmatch(r"board\d+\.py", f)),
                  key=lambda b: int(b[5:]))


def board_block(bid):
    L = []
    src = open(os.path.join(BOARDS, bid + ".py")).read()
    m = re.search(r'^COMPONENTS_MODULE\s*=\s*["\'](\w+)["\']', src, re.M)
    mod = m.group(1) if m else f"components_{bid}"
    try:
        C = importlib.import_module(mod)
        comps = list(C.COMPONENTS)
    except Exception as e:                       # report, never hide
        return [f"**{bid}:** value bus `studies/{mod}.py` failed to import: {e}", ""]
    counts = {}
    for c in comps:
        counts[c[3]] = counts.get(c[3], 0) + 1
    L.append(f"**{bid} components:** {counts.get('set', 0)} set · "
             f"{counts.get('proposed', 0)} proposed · {counts.get('tbd', 0)} "
             f"placeholder (of {len(comps)}).")
    open_rows = [c for c in comps if c[3] != "set"]
    if open_rows:
        L += ["", "| ref | function | value/spec | status |", "|---|---|---|---|"]
        L += [f"| {r} | {f} | {v} | {st} |" for r, f, v, st, *_ in open_rows]
    r = subprocess.run([PY, os.path.join(HERE, "handoff", "publish.py"),
                        "--check", "--board", bid], capture_output=True, text=True)
    first = (r.stdout.strip().splitlines() or [r.stderr.strip() or "no output"])[0]
    first = re.sub(rf"^{bid}:\s*", "", first)
    L += ["", f"**{bid} handoff:** {first}", ""]
    return L


def block():
    L = ["*Generated by tools/status.py — do not edit.*", ""]
    bs = boards()
    if not bs:
        L += ["**Boards:** none yet (`./setup.sh new-board N slug \"Title\"`).", ""]
    for bid in bs:
        L += board_block(bid)
    gd = os.path.join(HERE, "diagrams")
    sheets = []
    for g in sorted(os.listdir(gd)) if os.path.isdir(gd) else []:
        src = open(os.path.join(gd, g)).read() if g.endswith(".py") else ""
        out = re.search(r'^OUTPUT\s*=\s*["\']([^"\']+)["\']', src, re.M)
        ref = re.search(r'^REFLECTS\s*=\s*["\']([^"\']+)["\']', src, re.M)
        if out:
            sheets.append(f"{os.path.basename(out.group(1))} (reflects {ref.group(1) if ref else '?'})")
    L.append("**Diagrams:** " + (" · ".join(sheets) or "none"))
    return "\n".join(L) + "\n"


def main():
    p = os.path.join(ROOT, "design", "STATUS.md")
    s = open(p).read()
    i, j = s.index(A) + len(A), s.index(B)
    new = s[:i] + "\n" + block() + s[j:]
    if "--check" in sys.argv:
        if new != s:
            print("design/STATUS.md: the generated block is not current -- run tools/status.py")
            return 1
        return 0
    with open(p, "w") as f:
        f.write(new)
    print("STATUS.md generated block updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
