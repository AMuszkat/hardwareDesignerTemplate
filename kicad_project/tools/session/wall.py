#!/usr/bin/env python3
"""
PreToolUse hook on Edit|Write|NotebookEdit -- the ownership walls, made
mechanical.

    python3 <kicad_project>/tools/session/wall.py board     (board sessions)
    python3 <kicad_project>/tools/session/wall.py concept   (the concept session)

BOARD side.  All board sessions share kicad_project/.claude/, so a permission
rule cannot say "board1's session may write board1_main/ and not
board2_power/".  The launcher can: `bin/board board1` exports HW_BOARD=board1,
and the session-start hook records that as this session's claim
(tools/boardsel.py `owner`: HW_BOARD, else the claim, else the only board).

  * a board's handoff/ (generated by concept)              -> block
  * the session's board known, target in another board     -> block
  * the board NOT known (resumed outside bin/board with no
    claim, and more than one board), target in a board     -> block, with the
                                                              line to run

The board side never ASKS.  An `ask` parks an unattended session on a prompt
nobody sees: two board sessions lost 20 hours each to exactly that, so the
unknown case is a refusal the session can read and act on (tell the user to
restart it with `bin/board boardN --resume`), not a question to a user who is
not there.

CONCEPT side.  Why a hook and not deny rules: a session started in
kicad_project/ also loads the ROOT's .claude/settings.local.json deny rules, so
a concept wall written there would wall the board sessions out of their own
folders.  The root's settings.json hooks are not loaded there, so this is.

  * a board folder, kicad_project/tools/, kicad_project/.claude/ -> block (theirs)
  * project.json, relay.json, local.json,
    local.sessions.json                                    -> block (setup.sh / bin/relay / the brief)
  * RELAY_PROTOCOL.md, kicad_project/CLAUDE.md, .mcp.json  -> ask (the user's)
  * a GENERATED file: design/diagrams/*.svg, any handoff/,
    reference/vendor/datasheets.json, studies/baselines/*,
    tools/handoff/rulechecks/*  -> block (edit the generator)

Bash bypasses this, like every permission rule; the written contracts carry
the boundary there.  Exit 2 = block, reason on stderr.
"""
import json
import os
import re
import sys
from pathlib import Path

KP = Path(__file__).resolve().parents[2]
ROOT = KP.parent
sys.path.insert(0, str(KP / "tools"))


def block(msg):
    print(msg, file=sys.stderr)
    sys.exit(2)


def ask(reason):
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse",
                                             "permissionDecision": "ask",
                                             "permissionDecisionReason": reason}}))
    sys.exit(0)


def target(event):
    ti = event.get("tool_input") or {}
    raw = ti.get("file_path") or ti.get("notebook_path") or ""
    if not raw:
        return None
    cwd = event.get("cwd") or os.getcwd()
    return Path(raw if os.path.isabs(raw) else os.path.join(cwd, raw)).resolve()


def board_side(path, event):
    try:
        rel = path.relative_to(KP)
    except ValueError:
        return
    m = re.fullmatch(r"(board\d+)_\w+", rel.parts[0]) if rel.parts else None
    if not m:
        return
    if len(rel.parts) > 1 and rel.parts[1] == "handoff":
        block(f"{rel} is generated by the concept session and read-only here: your edit "
              "would vanish at the next publish. A defect in it is a QUESTIONS.md entry.")
    from boardsel import owner
    mine, _how = owner(event.get("session_id"))
    if not mine:
        block("This session does not know which board it owns: it was not started with "
              "bin/board, and it has no claim from an earlier start. Edit and Write in a "
              f"board folder ({rel.parts[0]}/) are refused until the user restarts it with "
              "`bin/board boardN --resume` (from the repo root; pick this session in the "
              "list). Tell the user that line now and stop writing board files; do not work "
              "around the wall through Bash.")
    if m.group(1) != mine:
        block(f"{rel.parts[0]}/ belongs to another board session; you are {mine}. Board "
              "sessions never write each other's folders -- a cross-board fact goes to the "
              "concept session as a QUESTIONS.md entry.")


GENERATED = [
    (re.compile(r"design/diagrams/[^/]+\.svg"), "generated by tools/diagrams/ -- edit the "
     "generator and re-run it; a hand-edited sheet fails lint check 4"),
    (re.compile(r"kicad_project/board\d+_\w+/handoff/.*"), "generated by "
     "tools/handoff/publish.py -- change the board's data module or value bus and publish"),
    (re.compile(r"reference/vendor/datasheets\.json"), "the datasheet index, written by "
     "tools/parts/datasheet.py -- use --url / --file to file a datasheet"),
    (re.compile(r"studies/baselines/.*"), "written by run_all.py --check --bless, after "
     "you have looked at the deltas"),
    (re.compile(r"tools/handoff/rulechecks/.*"), "the rule proofs, written by "
     "tools/review/rulecheck.py -- run it; a typed proof is ignored"),
]


def concept_side(path, _event=None):
    try:
        rel = path.relative_to(ROOT).as_posix()
    except ValueError:
        return
    for rx, why in GENERATED:
        if rx.fullmatch(rel):
            block(f"{rel} is {why}.")
    if not rel.startswith("kicad_project/"):
        return
    sub = rel[len("kicad_project/"):]
    first = sub.split("/", 1)[0]
    if re.fullmatch(r"board\d+_\w+", first):
        block(f"{rel} belongs to that board's session. Answer in "
              "tools/handoff/answers/boardN.md and publish; never write in their files.")
    if first in ("tools", ".claude"):
        block(f"{rel} belongs to the board sessions (kicad_project/{first}/). Ask the user.")
    if sub in ("project.json", "relay.json", "local.json", "local.sessions.json"):
        block(f"{rel} is written by ./setup.sh init, bin/relay and the session-start hook, "
              "never by hand.")
    if sub == "RELAY_PROTOCOL.md":
        ask("RELAY_PROTOCOL.md is the user's protocol: both sessions follow it and neither "
            "edits it. Confirm the user asked for this change.")
    if sub in ("CLAUDE.md", ".mcp.json"):
        ask(f"kicad_project/{sub} defines the board sessions (their contract, their MCP "
            "servers); it is the user's. Confirm the user asked for this change.")


def main():
    side = sys.argv[1] if len(sys.argv) > 1 else "board"
    try:
        event = json.load(sys.stdin)
    except json.JSONDecodeError:
        sys.exit(0)
    path = target(event)
    if path is None:
        sys.exit(0)
    (concept_side if side == "concept" else board_side)(path, event)
    sys.exit(0)


if __name__ == "__main__":
    main()
